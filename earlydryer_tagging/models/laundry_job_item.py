from collections import defaultdict

from markupsafe import Markup

from odoo import api, fields, models
from odoo.exceptions import AccessError, UserError, ValidationError
from odoo.tools.misc import format_datetime

from .earlydryer_tag_code import normalize_code

FRONT_DESK_GROUP = "earlydryer_base.group_front_desk"
MANAGER_GROUP = "earlydryer_base.group_branch_manager"
# jobs whose tags are free again (pre-printed tags are reused)
CLOSED_STATES = ("delivered", "collected", "uncollected", "cancelled")
# context key: the codes being written were generated by the tag sequence
TAG_GENERATED_CTX = "earlydryer_tag_generated"
# item fields this module changes after intake (see _earlydryer_check_locked)
TAG_OPEN_FIELDS = {"packed_scanned", "packed_scanned_on", "tag_print_count"}


class LaundryJobItem(models.Model):
    _inherit = "laundry.job.item"

    tag_required = fields.Boolean(
        related="service_type_id.requires_tag", string="Needs a Tag"
    )
    tag_mode = fields.Selection(related="earlydryer_branch_id.tag_mode")
    packed_scanned = fields.Boolean(
        string="Scanned at Packing",
        copy=False,
        readonly=True,
        help="Set when the garment is scanned on the packing screen; reset when "
        "the job goes back for rework.",
    )
    packed_scanned_on = fields.Datetime(
        string="Packing Scan", copy=False, readonly=True
    )
    tag_print_count = fields.Integer(
        string="Tag Prints",
        copy=False,
        readonly=True,
        help="Times the tag was printed.",
    )
    tag_history_ids = fields.One2many(
        "earlydryer.tag.history", "item_id", string="Replaced Tags", readonly=True
    )

    # laundry_order made the code unique per plant; pre-printed tags must be
    # reusable once the order is closed, so the unique index is replaced by a
    # plain one (same name: 19 drops and recreates it when the definition
    # changes) and uniqueness is checked in _check_tag_code_unique.
    _tag_branch_uniq = models.Index(
        "(earlydryer_branch_id, tag_code) WHERE tag_code IS NOT NULL"
    )

    # ------------------------------------------------------------------
    # Constraints
    # ------------------------------------------------------------------

    def _earlydryer_tag_holder(self, code):
        """Other item holding ``code`` the way this item's plant counts it
        (printed: any job, ever; pre-printed: open jobs of the plant)."""
        self.ensure_one()
        Item = self.sudo().with_context(active_test=False)
        branch = self.earlydryer_branch_id
        if branch.tag_mode == "preprinted":
            domain = [
                ("earlydryer_branch_id", "=", branch.id),
                ("job_state", "not in", CLOSED_STATES),
            ]
        else:
            domain = [("company_id", "=", self.company_id.id)]
        return Item.search(
            [("tag_code", "=", code), ("id", "!=", self.id), *domain], limit=1
        )

    @api.constrains("tag_code", "job_id")
    def _check_tag_code_unique(self):
        History = self.env["earlydryer.tag.history"].sudo()
        for item in self.filtered("tag_code"):
            other = item._earlydryer_tag_holder(item.tag_code)
            if other:
                raise ValidationError(
                    self.env._(
                        "Tag %(code)s is already on job %(job)s.",
                        code=item.tag_code,
                        job=other.job_id.name,
                    )
                )
            if item.earlydryer_branch_id.tag_mode == "printed":
                replaced = History.search(
                    [
                        ("old_code", "=", item.tag_code),
                        ("company_id", "=", item.company_id.id),
                    ],
                    limit=1,
                )
                if replaced:
                    raise ValidationError(
                        self.env._(
                            "Tag %(code)s was replaced on job %(job)s and stays "
                            "reserved.",
                            code=item.tag_code,
                            job=replaced.job_id.name,
                        )
                    )

    def _earlydryer_check_tag_format(self):
        """Codes typed, scanned or synced must be valid for their plant; codes
        of a till's tag range are consumed."""
        TagCode = self.env["earlydryer.tag.code"]
        Range = self.env["earlydryer.tag.range"]
        for item in self.filtered("tag_code"):
            branch = item.earlydryer_branch_id
            if not TagCode.is_valid_for_branch(item.tag_code, branch):
                if branch.tag_mode == "preprinted":
                    message = self.env._(
                        "%(code)s does not look like a tag of plant %(branch)s.",
                        code=item.tag_code,
                        branch=branch.display_name,
                    )
                else:
                    message = self.env._(
                        "%(code)s is not a valid tag code of plant %(branch)s "
                        "(wrong prefix or check digit).",
                        code=item.tag_code,
                        branch=branch.display_name,
                    )
                raise ValidationError(message)
            if branch.tag_mode == "printed":
                Range._earlydryer_consume(item.tag_code, branch)

    # ------------------------------------------------------------------
    # CRUD
    # ------------------------------------------------------------------

    def _earlydryer_check_locked(self, jobs, fnames=None):
        if fnames is not None:
            fnames = set(fnames) - TAG_OPEN_FIELDS
            if not fnames:
                return
        return super()._earlydryer_check_locked(jobs, fnames)

    @api.model_create_multi
    def create(self, vals_list):
        for vals in vals_list:
            if vals.get("tag_code"):
                vals["tag_code"] = normalize_code(vals["tag_code"])
        items = super().create(vals_list)
        if not self.env.context.get(TAG_GENERATED_CTX):
            items._earlydryer_check_tag_format()
        items._earlydryer_auto_assign_tags()
        return items

    def write(self, vals):
        if vals.get("tag_code"):
            vals["tag_code"] = normalize_code(vals["tag_code"])
        if "tag_code" in vals and not self.env.context.get(TAG_GENERATED_CTX):
            self._earlydryer_check_tag_write(vals["tag_code"])
        res = super().write(vals)
        if vals.get("tag_code") and not self.env.context.get(TAG_GENERATED_CTX):
            self._earlydryer_check_tag_format()
        return res

    def _earlydryer_check_tag_write(self, code):
        """Typing over an existing tag is a replacement (wizard, with a reason);
        removing a printed tag would lose the code."""
        if self.env.su or self.env.user.has_group(MANAGER_GROUP):
            return
        for item in self.filtered("tag_code"):
            if item.tag_code != code:
                raise AccessError(
                    self.env._(
                        "Item %(item)s already has tag %(code)s: use Replace Tag.",
                        item=item.display_name,
                        code=item.tag_code,
                    )
                )

    # ------------------------------------------------------------------
    # Assignment
    # ------------------------------------------------------------------

    def _earlydryer_needs_tag(self):
        """Items that need a tag and have none."""
        return self.filtered(lambda item: item.tag_required and not item.tag_code)

    def _earlydryer_assign_generated_codes(self):
        """Printed plants: give a new code to each item needing one.

        :returns: the items that got a code
        """
        TagCode = self.env["earlydryer.tag.code"]
        todo = self._earlydryer_needs_tag().filtered(
            lambda item: item.earlydryer_branch_id.tag_mode == "printed"
        )
        by_branch = defaultdict(lambda: self.browse())
        for item in todo:
            by_branch[item.earlydryer_branch_id] |= item
        for branch, items in by_branch.items():
            codes = TagCode._generate_many(branch, len(items))
            for item, code in zip(items, codes, strict=True):
                item.with_context(**{TAG_GENERATED_CTX: True}).tag_code = code
        return todo

    def _earlydryer_auto_assign_tags(self):
        """At intake, in printed plants assigning tags automatically."""
        items = self.filtered(
            lambda item: (
                item.job_id.state == "received"
                and item.earlydryer_branch_id.tag_mode == "printed"
                and item.earlydryer_branch_id.tag_auto_assign
            )
        )
        if items._earlydryer_needs_tag():
            items.sudo()._earlydryer_assign_generated_codes()

    # ------------------------------------------------------------------
    # Replacement
    # ------------------------------------------------------------------

    def _earlydryer_check_can_replace(self):
        if self.env.su or self.env.user.has_group(MANAGER_GROUP):
            return
        for item in self:
            if item.earlydryer_branch_id.tag_mode != "preprinted" or not (
                self.env.user.has_group(FRONT_DESK_GROUP)
            ):
                raise AccessError(
                    self.env._(
                        "Only a Branch Manager can replace a printed tag (front desk "
                        "staff can replace pre-printed tags)."
                    )
                )

    def _earlydryer_replace_tag(self, reason, new_code=None):
        """Replace the lost or damaged tag of this item.

        :param reason: why (required, logged)
        :param new_code: the scanned code of the new tag; printed plants
            generate one when empty
        :returns: the new code
        """
        self.ensure_one()
        self._earlydryer_check_can_replace()
        if not (reason or "").strip():
            raise UserError(self.env._("Give the reason for replacing the tag."))
        if self.job_id.state in CLOSED_STATES:
            raise UserError(self.env._("Job %(job)s is closed.", job=self.job_id.name))
        branch = self.earlydryer_branch_id
        new_code = normalize_code(new_code)
        old_code = self.tag_code
        if new_code and new_code == old_code:
            raise UserError(self.env._("The new tag must differ from the old one."))
        if not new_code and branch.tag_mode != "printed":
            raise UserError(self.env._("Scan the new pre-printed tag."))
        item = self.sudo()
        if old_code:
            self.env["earlydryer.tag.history"].sudo().create(
                {
                    "item_id": self.id,
                    "old_code": old_code,
                    "reason": reason,
                    "user_id": self.env.uid,
                }
            )
        if new_code:
            item.tag_code = new_code
        else:
            item.with_context(**{TAG_GENERATED_CTX: True}).tag_code = self.env[
                "earlydryer.tag.code"
            ].generate(branch)
        if old_code:
            item.tag_history_ids.filtered(lambda h: h.old_code == old_code).write(
                {"new_code": item.tag_code}
            )
        self.job_id.message_post(
            body=Markup("%s<br/>%s")
            % (
                self.env._(
                    "Tag of %(item)s replaced: %(old)s → %(new)s by %(user)s.",
                    item=item.product_id.display_name,
                    old=old_code or "-",
                    new=item.tag_code,
                    user=self.env.user.name,
                ),
                reason,
            ),
            subtype_xmlid="mail.mt_note",
        )
        return item.tag_code

    def action_open_replace_tag_wizard(self):
        self.ensure_one()
        self._earlydryer_check_can_replace()
        return {
            "type": "ir.actions.act_window",
            "name": self.env._("Replace Tag"),
            "res_model": "earlydryer.tag.replace.wizard",
            "view_mode": "form",
            "target": "new",
            "context": {"default_item_id": self.id},
        }

    # ------------------------------------------------------------------
    # Labels
    # ------------------------------------------------------------------

    def _earlydryer_label_values(self):
        """Plain values printed on the garment tag (PDF and ZPL)."""
        self.ensure_one()
        job = self.job_id
        return {
            "code": self.tag_code or "",
            "job": job.name or "",
            "garment": self.garment_category_id.name or "",
            "service": self.service_type_id.code or "",
            "piece": f"{self.piece_index}/{self.piece_count}"
            if self.piece_count > 1
            else "",
            "customer": job._earlydryer_customer_short_name(),
            "promised": format_datetime(
                self.env, job.promised_on, dt_format="dd/MM HH:mm"
            )
            if job.promised_on
            else "",
            "express": self.env._("EXPRESS") if job.express else "",
            "branch": job.earlydryer_branch_id.code or "",
        }
